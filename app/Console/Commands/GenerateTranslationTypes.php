<?php

namespace App\Console\Commands;

use App\Support\FrontendTranslations;
use Illuminate\Console\Command;

class GenerateTranslationTypes extends Command
{
    protected $signature = 'translations:types {--check : Fail if the generated file is out of date instead of writing it}';

    protected $description = 'Generate the TypeScript type of the translation keys available to the frontend t() helper';

    public function handle(): int
    {
        $path = self::path();
        $contents = self::render();

        if ($this->option('check')) {
            if (! is_file($path) || self::normalize((string) file_get_contents($path)) !== $contents) {
                $this->error('resources/js/types/translations.ts is out of date. Run: php artisan translations:types');

                return self::FAILURE;
            }

            $this->info('Translation types are up to date.');

            return self::SUCCESS;
        }

        file_put_contents($path, $contents);

        $this->info('Wrote '.count(FrontendTranslations::keys()).' translation keys to resources/js/types/translations.ts');

        return self::SUCCESS;
    }

    public static function path(): string
    {
        return resource_path('js/types/translations.ts');
    }

    public static function render(): string
    {
        $keys = FrontendTranslations::keys();

        $union = $keys === []
            ? 'never'
            : "\n".implode("\n", array_map(fn (string $key): string => "    | '{$key}'", $keys));

        return <<<TS
        // Generated by `php artisan translations:types` from lang/ — do not edit by hand.

        export type TranslationKey ={$union};

        TS;
    }

    /**
     * Compare without regard to line endings (git may check files out with CRLF on Windows).
     */
    public static function normalize(string $contents): string
    {
        return str_replace("\r\n", "\n", $contents);
    }
}
