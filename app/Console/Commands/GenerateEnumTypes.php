<?php

namespace App\Console\Commands;

use App\Enums\PermitStatus;
use App\Enums\PermitType;
use App\Enums\Recommendation;
use App\Enums\Role;
use App\Enums\VehicleRole;
use BackedEnum;
use Illuminate\Console\Command;

class GenerateEnumTypes extends Command
{
    /**
     * The enums the frontend needs, with the name of the generated list of values.
     *
     * @var array<class-string<BackedEnum>, string>
     */
    public const array ENUMS = [
        PermitStatus::class => 'PERMIT_STATUSES',
        PermitType::class => 'PERMIT_TYPES',
        VehicleRole::class => 'VEHICLE_ROLES',
        Recommendation::class => 'RECOMMENDATIONS',
        Role::class => 'ROLES',
    ];

    /** Prettier's print width: a list that fits on one line must be written on one line. */
    private const int PRINT_WIDTH = 80;

    protected $signature = 'enums:types {--check : Fail if the generated file is out of date instead of writing it}';

    protected $description = 'Generate the TypeScript types of the PHP enums the frontend uses';

    public function handle(): int
    {
        $path = self::path();
        $contents = self::render();

        if ($this->option('check')) {
            if (! is_file($path) || GenerateTranslationTypes::normalize((string) file_get_contents($path)) !== $contents) {
                $this->error('resources/js/types/enums.ts is out of date. Run: php artisan enums:types');

                return self::FAILURE;
            }

            $this->info('Enum types are up to date.');

            return self::SUCCESS;
        }

        file_put_contents($path, $contents);

        $this->info('Wrote '.count(self::ENUMS).' enums to resources/js/types/enums.ts');

        return self::SUCCESS;
    }

    public static function path(): string
    {
        return resource_path('js/types/enums.ts');
    }

    /**
     * @param  array<class-string<BackedEnum>, string>|null  $enums
     */
    public static function render(?array $enums = null): string
    {
        $blocks = [];

        foreach ($enums ?? self::ENUMS as $enum => $constant) {
            $type = class_basename($enum);
            $values = array_map(fn (BackedEnum $case): string => "'{$case->value}'", $enum::cases());

            $list = "export const {$constant} = [".implode(', ', $values).'] as const;';

            if (strlen($list) > self::PRINT_WIDTH) {
                $list = "export const {$constant} = [\n".implode('', array_map(fn (string $value): string => "    {$value},\n", $values)).'] as const;';
            }

            $blocks[] = <<<TS
            /** Mirrors App\\Enums\\{$type}. */
            {$list}

            export type {$type} = (typeof {$constant})[number];
            TS;
        }

        $body = implode("\n\n", $blocks);

        return <<<TS
        // Generated by `php artisan enums:types` from app/Enums — do not edit by hand.

        {$body}

        TS;
    }
}
