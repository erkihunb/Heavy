<?php

use App\Console\Commands\GenerateEnumTypes;
use App\Enums\PermitStatus;
use App\Enums\PermitType;
use App\Enums\Recommendation;
use App\Enums\Role;
use App\Enums\VehicleRole;
use Illuminate\Support\Facades\File;

/*
 * resources/js/types/enums.ts is generated from the PHP enums and committed;
 * CI runs `enums:types --check`. The tests that write a file point the
 * application at a temporary directory, so the real file is never touched.
 */

/**
 * Runs the callback with the application's base path moved to an empty
 * temporary directory that has a resources/js/types folder.
 */
function withTemporaryBasePath(Closure $callback): void
{
    $original = base_path();
    $temporary = storage_path('framework/testing/enum-types-'.bin2hex(random_bytes(6)));

    File::ensureDirectoryExists($temporary.'/resources/js/types');

    try {
        app()->setBasePath($temporary);

        $callback();
    } finally {
        app()->setBasePath($original);
        File::deleteDirectory($temporary);
    }
}

it('keeps the committed TypeScript enums in sync with the PHP enums', function () {
    $this->artisan('enums:types --check')->assertSuccessful();
});

it('generates the values and the type of every enum the frontend uses', function (string $enum, string $constant) {
    $typescript = GenerateEnumTypes::render();
    $type = class_basename($enum);

    expect($typescript)
        ->toContain("export const {$constant} = [")
        ->toContain("export type {$type} = (typeof {$constant})[number];")
        ->toContain("/** Mirrors App\\Enums\\{$type}. */");

    foreach ($enum::cases() as $case) {
        expect($typescript)->toContain("'{$case->value}'");
    }
})->with([
    [PermitStatus::class, 'PERMIT_STATUSES'],
    [PermitType::class, 'PERMIT_TYPES'],
    [VehicleRole::class, 'VEHICLE_ROLES'],
    [Recommendation::class, 'RECOMMENDATIONS'],
    [Role::class, 'ROLES'],
]);

it('lists the values in the order of the PHP enum', function () {
    $typescript = GenerateEnumTypes::render([PermitType::class => 'PERMIT_TYPES', PermitStatus::class => 'PERMIT_STATUSES']);

    expect($typescript)->toContain("export const PERMIT_TYPES = ['full_day', 'pass'] as const;");

    $positions = array_map(
        fn (PermitStatus $status): int => (int) strpos($typescript, "    '{$status->value}',"),
        PermitStatus::cases(),
    );
    $sorted = $positions;
    sort($sorted);

    expect($positions)->toBe($sorted)
        ->and(min($positions))->toBeGreaterThan(0)
        // The computed "active" status is part of the type the frontend uses.
        ->and($typescript)->toContain("'active'");
});

it('marks the file as generated and ends it with a newline', function () {
    $typescript = GenerateEnumTypes::render();

    expect($typescript)->toStartWith('// Generated by `php artisan enums:types`')
        ->toEndWith(";\n")
        ->not->toContain("\r");
});

it('fails the check when the generated file is stale', function () {
    withTemporaryBasePath(function () {
        file_put_contents(
            GenerateEnumTypes::path(),
            str_replace("'withdrawn',", "'withdrawn',\n    'archived',", GenerateEnumTypes::render()),
        );

        $this->artisan('enums:types --check')
            ->expectsOutputToContain('out of date')
            ->assertFailed();
    });
});

it('fails the check when the generated file is missing', function () {
    withTemporaryBasePath(function () {
        $this->artisan('enums:types --check')->assertFailed();

        // The check never writes.
        expect(is_file(GenerateEnumTypes::path()))->toBeFalse();
    });
});

it('writes the file, after which the check passes', function () {
    withTemporaryBasePath(function () {
        $this->artisan('enums:types')->assertSuccessful();

        expect(file_get_contents(GenerateEnumTypes::path()))->toBe(GenerateEnumTypes::render());

        $this->artisan('enums:types --check')->assertSuccessful();
    });
});

it('accepts a checkout with Windows line endings', function () {
    withTemporaryBasePath(function () {
        file_put_contents(GenerateEnumTypes::path(), str_replace("\n", "\r\n", GenerateEnumTypes::render()));

        $this->artisan('enums:types --check')->assertSuccessful();
    });
});

it('never touches the committed file', function () {
    $path = GenerateEnumTypes::path();
    $before = [md5_file($path), filemtime($path)];

    withTemporaryBasePath(function () use ($path) {
        expect(GenerateEnumTypes::path())->not->toBe($path);

        $this->artisan('enums:types')->assertSuccessful();
    });

    clearstatcache();

    expect(GenerateEnumTypes::path())->toBe($path)
        ->and([md5_file($path), filemtime($path)])->toBe($before);
});
